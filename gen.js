G.nvt = function(c, standalone=true){
  let s = standalone ? header(c,'3a. NVT equilibration') : '# ---- 3a. NVT equilibration ----\n';
  s += nvtMdp(c) + S`

$GMX grompp -f nvt.mdp -c {{p_em}}.gro -r {{p_em}}.gro -p {{top}} -o {{p_nvt}}.tpr
$GMX mdrun -deffnm {{p_nvt}} {{mdrun}}

printf "Temperature\n0\n" | $GMX energy -f {{p_nvt}}.edr -o temperature_nvt.xvg -xvg none
`;
  return fill(s,c);
};
G.npt = function(c, standalone=true){
  let s = standalone ? header(c,'3b. NPT equilibration') : '# ---- 3b. NPT equilibration ----\n';
  s += nptMdp(c) + S`

$GMX grompp -f npt.mdp -c {{p_nvt}}.gro -r {{p_nvt}}.gro -t {{p_nvt}}.cpt -p {{top}} -o {{p_npt}}.tpr
$GMX mdrun -deffnm {{p_npt}} {{mdrun}}

printf "Pressure\n0\n" | $GMX energy -f {{p_npt}}.edr -o pressure_npt.xvg -xvg none
printf "Density\n0\n"  | $GMX energy -f {{p_npt}}.edr -o density_npt.xvg -xvg none
`;
  return fill(s,c);
};
G.equil = function(c, standalone=true){
  let s = standalone ? header(c,'3. Equilibration (NVT then NPT)') : '';
  s += G.nvt(c,false) + '\n' + G.npt(c,false);
  return s;
};

G.prod = function(c, standalone=true){
  const cm = common(c);
  const nsteps = stepsFromPs(c.md_ns*1000, c.dt);
  let s = standalone ? header(c,'4. Production run') : '# ---- 4. Production run ----\n';
  s += heredoc('md.mdp', S`
title                   = Production MD
integrator              = md
dt                      = {{dt}}
nsteps                  = ` + nsteps + S`   ; {{md_ns}} ns
nstenergy               = 5000
nstlog                  = 5000
nstcalcenergy           = 100
continuation            = yes
constraint-algorithm    = lincs
constraints             = h-bonds
lincs-iter              = 1
lincs-order             = 4
tcoupl                  = V-rescale
tc-grps                 = Protein Non-Protein
tau-t                   = 0.1     0.1
ref-t                   = {{temp}}     {{temp}}
pcoupl                  = Parrinello-Rahman
pcoupltype              = isotropic
tau-p                   = 2.0
ref-p                   = 1.0
compressibility         = 4.5e-5
gen-vel                 = no
` + cm.block + S`
` + outTraj(c)) + S`

$GMX grompp -f md.mdp -c {{p_npt}}.gro -t {{p_npt}}.cpt -p {{top}} -o {{p_md}}.tpr
$GMX mdrun -deffnm {{p_md}} -v {{mdrun}}
# Resume after interruption:  $GMX mdrun -deffnm {{p_md}} -cpi {{p_md}}.cpt -append
`;
  return fill(s,c);
};

G.pbc = function(c, standalone=true){
  let s = standalone ? header(c,'5. PBC correction') : '# ---- 5. PBC correction ----\n';
  s += S`
# a) make molecules whole, center protein, compact unit cell (groups: Protein, System)
printf "Protein\nSystem\n" | $GMX trjconv -s {{p_md}}.tpr -f {{p_md}}.{{traj}} -o {{p_md}}_center.{{traj}} -pbc mol -center -ur compact

# b) remove rotation/translation (fit group Backbone, output group System)
printf "Backbone\nSystem\n" | $GMX trjconv -s {{p_md}}.tpr -f {{p_md}}_center.{{traj}} -o {{p_md}}_fit.{{traj}} -fit rot+trans

# c) centered reference frame (for visualization)
printf "Protein\nSystem\n" | $GMX trjconv -s {{p_md}}.tpr -f {{p_md}}.{{traj}} -o {{p_md}}_center.gro -pbc mol -center -ur compact -dump 0

# Open in VMD: vmd {{p_md}}_center.gro {{p_md}}_fit.{{traj}}
# Multi-chain / complex systems: add -pbc whole first, then -pbc nojump, then -pbc mol -center.
# Solvent-free output (smaller): choose Protein as output group in step b.
`;
  return fill(s,c);
};

