/* Script generators. Tokens {{name}} are replaced from the settings. */
const S = String.raw;
function fill(t, c){ return t.replace(/\{\{(\w+)\}\}/g, (m,k)=> (c[k]!==undefined? c[k] : m)); }

function ffParams(c){
  const f = c.ff || '';
  if(/^charmm/.test(f)) return {rc:1.2, rv:1.2, extra:S`vdwtype                 = cutoff
vdw-modifier            = force-switch
rvdw-switch             = 1.0
DispCorr                = no`, note:'CHARMM settings: 1.2 nm cutoffs with force-switch.'};
  if(/^gromos/.test(f)) return {rc:1.4, rv:1.4, extra:S`vdwtype                 = cutoff
vdw-modifier            = potential-shift
DispCorr                = EnerPres`, note:'GROMOS settings: 1.4 nm cutoffs.'};
  if(/^oplsaa/.test(f)) return {rc:1.2, rv:1.2, extra:S`vdwtype                 = cutoff
vdw-modifier            = potential-shift
DispCorr                = EnerPres`, note:'OPLS-AA settings: 1.2 nm cutoffs.'};
  return {rc:1.0, rv:1.0, extra:S`vdwtype                 = cutoff
vdw-modifier            = potential-shift
DispCorr                = EnerPres`, note:'AMBER settings: 1.0 nm cutoffs.'};
}
function common(c){
  const p = ffParams(c);
  return {p, block: S`cutoff-scheme           = Verlet
nstlist                 = 10
pbc                     = xyz
coulombtype             = PME
rcoulomb                = ${p.rc}
rvdw                    = ${p.rv}
fourierspacing          = 0.12
pme-order               = 4
${p.extra}`};
}
function heredoc(name, body){ return 'cat > ' + name + " << 'EOF'\n" + body.trim() + '\nEOF'; }
function header(c, title){
  return '#!/bin/bash\n# ' + title + '\n# Generated by Virtual Bio-Chemist. Force field: ' + c.ff + ', water: ' + c.water + '\n# Check every parameter against the GROMACS manual for your version (gmx --version).\nset -euo pipefail\nGMX=' + c.gmx + '\n';
}
function stepsFromPs(ps, dt){ return Math.round(ps/dt); }
function outTraj(c){
  const n = Math.round(10/c.dt); // every 10 ps
  return c.traj==='trr'
   ? 'nstxout                 = ' + n*500 + '   ; trr coordinates (large files!)\nnstvout                 = ' + n*500 + '\nnstfout                 = 0'
   : 'nstxout-compressed      = ' + n + '   ; xtc frame every 10 ps\ncompressed-x-grps       = System';
}

const G = {};

G.prep = function(c, standalone=true){
  const solvFile = (c.water==='tip4p') ? 'tip4p.gro' : 'spc216.gro';
  const cm = common(c);
  let s = standalone ? header(c,'1. System preparation') : '# ---- 1. System preparation ----\n';
  s += S`
# Topology and processed coordinates (hydrogens rebuilt with -ignh)
$GMX pdb2gmx -f {{input}} -o {{proc}} -p {{top}} -i posre.itp -ff {{ff}} -water {{water}} -ignh

# Define the box
$GMX editconf -f {{proc}} -o newbox.gro -c -d {{dist}} -bt {{box}}

# Solvate
$GMX solvate -cp newbox.gro -cs ` + solvFile + S` -o solv.gro -p {{top}}

# Add ions (neutralize + {{conc}} M salt)
` + heredoc('ions.mdp', S`
integrator              = steep
emtol                   = 1000.0
emstep                  = 0.01
nsteps                  = 50000
` + cm.block) + S`

$GMX grompp -f ions.mdp -c solv.gro -p {{top}} -o ions.tpr
echo "SOL" | $GMX genion -s ions.tpr -o {{solv}} -p {{top}} -pname NA -nname CL -neutral -conc {{conc}}

echo "System ready: {{solv}} and {{top}}"
`;
  return fill(s,c);
};

G.em = function(c, alg, standalone=true){
  alg = alg || c.em || 'steep';
  const cm = common(c);
  const p = '{{p_em}}';
  let integ = alg==='cg'
    ? S`integrator              = cg
emtol                   = 1000.0
emstep                  = 0.01
nstcgsteep              = 1000
nsteps                  = 50000
constraints             = none
; cg cannot use constraints: bonds are flexible during minimization`
    : S`integrator              = steep
emtol                   = 1000.0
emstep                  = 0.01
nsteps                  = 50000`;
  let s = standalone ? header(c,'2. Energy minimization (' + (alg==='cg'?'conjugate gradient':'steepest descent') + ')') : '# ---- 2. Energy minimization (' + alg + ') ----\n';
  s += heredoc('minim.mdp', integ + '\nnstenergy               = 10\nnstlog                  = 100\n' + cm.block + '\n' + (alg==='cg' ? 'define                  = -DFLEXIBLE' : ''));
  s += S`

$GMX grompp -f minim.mdp -c {{solv}} -p {{top}} -o ` + p + S`.tpr
$GMX mdrun -v -deffnm ` + p + ' {{mdrun}}' + S`

# Check: potential energy should be negative and Fmax < emtol
printf "Potential\n0\n" | $GMX energy -f ` + p + S`.edr -o potential_` + p + S`.xvg -xvg none
tail -n 25 ` + p + S`.log | grep -E "converged|Potential Energy|Maximum force" || true
`;
  return fill(s,c);
};

