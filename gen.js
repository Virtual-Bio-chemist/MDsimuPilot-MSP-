const BASIC = ['rmsd','rmsf','rg','hbond','sasa','energy'];

G.analysis = function(c, ids, standalone=true){
  ids = ids && ids.length ? ids : BASIC;
  let s = standalone ? header(c,'5. Analysis (run after PBC correction)') : '# ---- 5. Analysis ----\n';
  s += '# Requires {{p_md}}_fit.{{traj}} from the PBC step\n';
  ids.forEach(id=>{ s += '\n# ' + A[id].label + '\n' + A[id].body + '\n'; });
  return fill(s,c);
};

G.plot = function(c){
  return S`#!/usr/bin/env python3
# Quick plot of GROMACS .xvg files:  python plot_xvg.py rmsd.xvg [more.xvg ...]
import sys
import numpy as np
import matplotlib.pyplot as plt

def read_xvg(fn):
    title, xl, yl, legend = fn, 'x', 'y', []
    for line in open(fn):
        if line.startswith('@'):
            if ' title ' in line: title = line.split('"')[1]
            elif 'xaxis' in line and 'label' in line: xl = line.split('"')[1]
            elif 'yaxis' in line and 'label' in line: yl = line.split('"')[1]
            elif ' legend "' in line: legend.append(line.split('"')[1])
    return np.loadtxt(fn, comments=('#', '@')), title, xl, yl, legend

for fn in sys.argv[1:]:
    d, t, xl, yl, lg = read_xvg(fn)
    d = np.atleast_2d(d)
    plt.figure(figsize=(6, 4))
    for i in range(1, d.shape[1]):
        plt.plot(d[:, 0], d[:, i], lw=1, label=lg[i-1] if i-1 < len(lg) else None)
    plt.title(t); plt.xlabel(xl); plt.ylabel(yl)
    if lg: plt.legend()
    plt.tight_layout(); plt.savefig(fn.rsplit('.', 1)[0] + '.png', dpi=200)
    print('saved', fn.rsplit('.', 1)[0] + '.png')
`;
};

G.full = function(c, alg){
  let s = header(c,'Full GROMACS workflow: preparation, EM, equilibration, production, PBC, analysis');
  s += '\n' + G.prep(c,false) + '\n' + G.em(c,alg,false) + '\n' + G.equil(c,false) + '\n' + G.prod(c,false) + '\n' + G.pbc(c,false) + '\n' + G.analysis(c,BASIC,false);
  return s;
};

